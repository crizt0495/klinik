import { pgTable, uuid, varchar, text, boolean, index, uniqueIndex, timestamp, date, jsonb } from "drizzle-orm/pg-core";
import { organizations, branches, users } from "./core";
import { patients, insuranceProviders, patientInsurances } from "./clinical";
import { visits } from "./appointment";
import { invoices } from "./billing";

export const bpjsSettings = pgTable(
  "bpjs_settings",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    organizationId: uuid("organization_id").notNull().references(() => organizations.id),
    enabled: boolean("enabled").notNull().default(false),
    mockMode: boolean("mock_mode").notNull().default(true),
    serviceBaseUrl: varchar("service_base_url", { length: 512 }),
    consId: varchar("cons_id", { length: 64 }),
    secretKey: varchar("secret_key", { length: 255 }),
    userKey: varchar("user_key", { length: 128 }),
    faskesCode: varchar("faskes_code", { length: 32 }),
    faskesName: varchar("faskes_name", { length: 255 }),
    lastTestedAt: timestamp("last_tested_at", { withTimezone: true }),
    lastTestStatus: varchar("last_test_status", { length: 255 }),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [uniqueIndex("bpjs_settings_org_idx").on(t.organizationId)],
);

