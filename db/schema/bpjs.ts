export const bpjsClaims = pgTable(
  "bpjs_claims",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    organizationId: uuid("organization_id").notNull().references(() => organizations.id),
    branchId: uuid("branch_id").references(() => branches.id),
    visitId: uuid("visit_id").references(() => visits.id),
    invoiceId: uuid("invoice_id").references(() => invoices.id),
    sepId: uuid("sep_id").references(() => bpjsSep.id),
    claimNumber: varchar("claim_number", { length: 64 }).notNull(),
    noSep: varchar("no_sep", { length: 32 }),
    noKartu: varchar("no_kartu", { length: 32 }),
    namaPeserta: varchar("nama_peserta", { length: 255 }),
    tglPelayanan: date("tgl_pelayanan"),
    tglPulang: date("tgl_pulang"),
    jenisPelayanan: varchar("jenis_pelayanan", { length: 32 }).notNull().default("RAWAT_JALAN"),
    diagnosa: varchar("diagnosa", { length: 32 }),
    detailDiagnosa: varchar("detail_diagnosa", { length: 64 }),
    jumlahBebanBiaya: varchar("jumlah_beban_biaya", { length: 32 }).notNull().default("0"),
    jumlahTagihan: varchar("jumlah_tagihan", { length: 32 }).notNull().default("0"),
    totalBy40: varchar("total_by_40", { length: 32 }).notNull().default("0"),
    totalBySouth: varchar("total_by_south", { length: 32 }).notNull().default("0"),
    ttlByGroup: varchar("ttl_by_group", { length: 32 }).notNull().default("0"),
    groupByJson: jsonb("group_by_json"),
    responseJson: jsonb("response_json"),
    status: varchar("status", { length: 32 }).notNull().default("DRAFT"),
    notes: text("notes"),
    submittedBy: uuid("submitted_by").references(() => users.id),
    submittedAt: timestamp("submitted_at", { withTimezone: true }),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [
    uniqueIndex("bpjs_claims_org_number_idx").on(t.organizationId, t.claimNumber),
    index("bpjs_claims_org_created_idx").on(t.organizationId, t.createdAt),
    index("bpjs_claims_visit_idx").on(t.visitId),
    index("bpjs_claims_status_idx").on(t.status),
  ],
);